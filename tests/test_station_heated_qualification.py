@pytest.fixture(scope='module')
def evidence(tmp_path_factory):
    root=tmp_path_factory.mktemp('heated-qualification')
    assert study.run(root/'source')['passed']
    assert study.run(root/'repeat',root/'source')['passed']
    return root/'source'


def test_complete_external_mean_matrix_and_both_thermal_constraints(evidence):
    p=read(evidence/'report.json')
    assert p['passed'] and p['external_native_comparison_passed']
    assert not p['external_continuum_comparison_passed']
    assert p['external_cases']==14 and p['spatial_cases']==6
    assert not p['turbulent'] and not p['station_usable'] and not p['validated']
    assert not p['npp_11_03_accepted'] and not p['r1_accepted'] and p['closed_tasks']==[]
    assert len(list(evidence.glob('*.json')))==5


def test_normalizations_do_not_identify_area_mean_with_mixing_cup(evidence):
    p=read(evidence/'normalizations.json');forced=p['heat_flux-0.0']
    assert forced['nusselt_area']==pytest.approx(6,rel=1e-5)
    assert forced['nusselt_mixing']==pytest.approx(48/11,rel=1e-5)
    assert forced['area_mean_temperature']==pytest.approx(1/3,abs=1e-6)
    # Cell-centre quadrature has an O(h^2) error in the mixing-cup mean.
    assert forced['mixing_cup_temperature']==pytest.approx(1/12,abs=.5/512**2)
    assert all(p['mapping-'+str(c)]['maximum_absolute']<1e-8 for c in (0.,2.,5.))


def test_grid_and_time_refinements_are_separate(evidence):
    s=read(evidence/'spatial.json');external=read(evidence/'external.json')
    assert all(min(v['orders'])>1.8 for v in s.values())
    assert max(external['time_refinement_absolute'].values())<2e-7
    assert all(v['late_maximum']<1e-7 and abs(v['time']-8000)<1e-6 for v in external['cases'].values())


def test_changed_criteria_cannot_reuse_old_protocol(evidence,tmp_path):
    p=read(evidence/'protocol.json');p['criteria']['external_profile_absolute']=1.
    ref=tmp_path/'wrong';ref.mkdir();atomic_json(ref/'protocol.json',seal(p))
    with pytest.raises(ValueError,match='identity'):study.run(tmp_path/'out',ref)
    assert not (tmp_path/'out').exists()


def test_external_profile_corruption_fails_comparison_gate(tmp_path,monkeypatch):
    source=load_external()
    first=next(v for v in source['records'].values() if v['cells']==64);first['final']['temperature'][0]+=.1
    monkeypatch.setattr(study,'load_external',lambda:source)
    with pytest.raises(ValueError,match='qualification failed'):study.run(tmp_path/'refused')
    assert not read(tmp_path/'refused/report.json')['passed']


def test_independent_initial_condition_and_no_model_generated_reference():
    p=load_external()
    assert p['subspace']==dict(axial_modes=1,azimuthal_modes=1,turbulent=False)
    assert 'no Atomic Sim profile used' in p['input']
    assert p['modifications'].startswith('Only listed parameters.f90')
    assert p['corrected_pdf_sha256']=='e56ad687c36cd8c34f45dce72a29891b2d13590d422ef6ec98dda185910999d0'
    # With C=0 no axial momentum perturbation is generated by the external solver.
    for row in p['records'].values():
        if row['c']==0:
            r=np.array(row['final']['radius']);u=np.array(row['final']['velocity'])
            np.testing.assert_allclose(u,1-r*r,rtol=0,atol=1e-15)


